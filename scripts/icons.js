/** 单个 symbol（仅几何；描边表现交给 .ico） */
function symbol(id, inner) {
  return '<symbol id="i-' + id + '" viewBox="0 0 24 24">' + inner + '</symbol>';
}

/** 全量雪碧图（每页注入一次；纯几何无文字，UTF-8 安全，体积数 KB） */
function fullSprite() {
  const syms = Object.keys(ICONS).map((k) => symbol(k, ICONS[k])).join('');
  return '<svg class="svg-sprite" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">' + syms + '</svg>';
}

/** 引用某图标 → <svg class="ico"><use href="#i-name"/></svg>；缺省回退 grid */
function iconRef(name, extraClass) {
  const key = Object.prototype.hasOwnProperty.call(ICONS, name) ? name : 'grid';
  const cls = 'ico' + (extraClass ? ' ' + extraClass : '');
  return '<svg class="' + cls + '" aria-hidden="true" focusable="false"><use href="#i-' + key + '"></use></svg>';
}

module.exports = { ICONS, fullSprite, iconRef };
